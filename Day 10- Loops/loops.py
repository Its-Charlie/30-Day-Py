#While Loop:
count = 0
while count < 5:
    print(count)
    count = count + 1

#while Loop with else:
count = 0
while count < 5:
    print(count)
    count = count + 1
else:
    print(count)

#while Loop with break:
count = 0
while count < 5:
    print(count)
    count = count + 1
    if count == 3:
        break