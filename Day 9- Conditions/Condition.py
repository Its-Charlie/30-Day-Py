#If condition:
a = 3
if a > 0:
    print('A is a positive number')
# A is a positive number

##If-else condition:
a = 3
if a < 0:
    print('A is a negative number')
else:
    print('A is a positive number')

#If-elif-else condition:
a = 0
if a > 0:
    print('A is a positive number')
elif a < 0:
    print('A is a negative number')
else:
    print('A is zero')